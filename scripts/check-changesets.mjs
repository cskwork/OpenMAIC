import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  PUBLISHABLE_PACKAGES,
  compareVersions,
  git,
  packageDirectory,
  readChangesetsConfig,
  readVersion,
  repositoryRoot,
  resolveCommit,
} from './openmaic-packages.mjs';

/**
 * The merge-time gate: every publishable @openmaic package changed between
 * `base` and HEAD must be named by a changeset added in that same range.
 *
 * This is the assertion the hand-maintained version bump used to make, restated
 * in changesets' terms. `changeset status` is not it: status fails only when the
 * range contains NO changesets at all, so changing the renderer while declaring
 * only storage passes it, and so does changing the renderer with
 * `changeset add --empty`. Per package, or the check does not bind.
 *
 * The empty changeset stays as the escape hatch, but it now has to be aimed:
 * work that touches no publishable input needs nothing, and work that touches
 * one has to name that package.
 *
 * The comparison is against the merge base and includes the working tree, which
 * is what `changeset status --since` does, so the two agree about what "changed
 * in this range" means.
 */

const usage = 'Usage: check-changesets.mjs <base-ref>';

const root = repositoryRoot();

const commonIgnoredInputs = {
  files: ['.gitignore', 'vitest.config.ts', 'CHANGELOG.md'],
  directories: ['docs/', 'test/'],
};

/**
 * Files under a package directory that never reach its tarball, so changing one
 * cannot change what consumers receive. Everything else counts, including
 * `scripts/`, `rollup.config.js` and `tsconfig.json`, because those decide what
 * the build emits.
 *
 * Per package rather than repository-wide on purpose: the `files` whitelists
 * differ between these packages — the renderer ships `DESIGN.md`, the importer
 * does not — so one shared list would have to be either wrong for someone or so
 * short that it stops being useful. An entry here that does ship turns a real
 * release into a silently skipped one, which is the failure this gate exists to
 * prevent, so the lists stay conservative.
 *
 * KNOWN LIMITATION: this treats "publishable input" as "file under the package
 * directory", which is an under-approximation for all four packages.
 *
 * Renderer and importer inline their dependency graph through Rollup, so a
 * lockfile-only resolution change rewrites their published bundles. Even dsl
 * and storage are not exempt: their dist is whatever the lockfile's TypeScript
 * emits, and dsl's shipped JSON schema is generated by the lockfile's
 * ts-json-schema-generator. A toolchain bump can therefore change any of the
 * four tarballs with no diff under the package directory.
 *
 * Closing this would mean treating the lockfile and toolchain configuration as
 * an input of every package, which makes every dependency bump demand four
 * changesets, or externalising the bundled dependencies. Both are decisions
 * about how the packages are built rather than about this check. This is a
 * merge-time guard against the common case, not a proof of byte equality.
 */
const ignoredPackageInputs = {
  '@openmaic/dsl': commonIgnoredInputs,
  '@openmaic/storage': commonIgnoredInputs,
  '@openmaic/renderer': commonIgnoredInputs,
  '@openmaic/importer': {
    // These are local tooling, demo assets, or the legacy reference
    // implementation. The importer build and package files exclude all of them.
    files: [
      ...commonIgnoredInputs.files,
      '.babelrc.cjs',
      '.eslintignore',
      '.eslintrc.cjs',
      'DESIGN.md',
      'SKILL.md',
      'favicon.ico',
      'index.html',
    ],
    directories: [...commonIgnoredInputs.directories, 'scripts/', 'src1/'],
  },
};

function gitFileAt(ref, file) {
  const path = git(['ls-tree', '--full-tree', '--name-only', ref, '--', file], { cwd: root });
  if (path === '') return undefined;
  return git(['show', `${ref}:${file}`], { cwd: root });
}

function mergeBase(base) {
  return git(['merge-base', base, 'HEAD'], { cwd: root });
}

function changedFiles(from, { filter = 'ACDMRT', pathspec } = {}) {
  const args = ['diff', '--name-only', '--no-renames', `--diff-filter=${filter}`, from];
  if (pathspec) args.push('--', ...pathspec);
  return git(args, { cwd: root }).split('\n').filter(Boolean);
}

/** Whether any publishable input of `name` differs from `from`. */
function publishableInputsChanged(name, from) {
  const directory = packageDirectory(name);
  const ignored = ignoredPackageInputs[name];
  const files = changedFiles(from, { pathspec: [directory] });
  // A package on the allowlist with no ignore list treats every file as an
  // input, rather than being silently exempted.
  if (!ignored) return files.length > 0;
  return files.some((file) => {
    const relative = file.slice(directory.length + 1);
    const isIgnored =
      ignored.files.includes(relative) ||
      ignored.directories.some((prefix) => relative.startsWith(prefix));
    return !isIgnored;
  });
}

/** Changeset files consumed in this range. */
function consumedChangesets(from) {
  return changedFiles(from, { filter: 'D', pathspec: ['.changeset'] }).filter(
    (file) => /^\.changeset\/[^/]+\.md$/.test(file) && !/README\.md$/i.test(file),
  );
}

/** Whether `name`'s manifest version strictly increased over the range. */
function versionIncreased(name, from) {
  const manifest = `${packageDirectory(name)}/package.json`;
  const beforeContents = gitFileAt(from, manifest);
  // A package that did not exist at the merge base has nothing to compare
  // against, so its presence cannot be read as a missing bump.
  if (beforeContents === undefined) return true;
  let afterContents;
  try {
    afterContents = readFileSync(join(root, manifest), 'utf8');
  } catch {
    return false;
  }
  try {
    const before = readVersion(beforeContents, `${manifest} at ${from}`);
    const after = readVersion(afterContents, `${manifest} in the working tree`);
    return compareVersions(after, before) > 0;
  } catch {
    return false;
  }
}

async function main(baseRef) {
  if (!resolveCommit(baseRef, root)) {
    console.error(`Base ref ${JSON.stringify(baseRef)} is not an available commit.`);
    process.exit(2);
  }
  const from = mergeBase(baseRef);

  const changed = PUBLISHABLE_PACKAGES.filter((name) => publishableInputsChanged(name, from));
  if (changed.length === 0) {
    console.log('No publishable @openmaic package input changed in this range.');
    return;
  }
  console.log(`Publishable inputs changed: ${changed.join(', ')}.`);

  // The release commit. `changeset version` consumes every pending changeset, so
  // the change that applies them alters packages with none left to find and can
  // never satisfy the check below — including on the pull request that carries
  // it, which is where branch protection looks first.
  //
  // It is recognised by what makes it legitimate — consumed changesets AND a
  // version increase for every changed package — rather than by an author or a
  // commit message, which anyone can write. Requiring the version increases is
  // what stops a change from buying an exemption by deleting somebody else's
  // pending changeset: that is the merge-time version assertion this gate
  // replaced, kept for the one case where a changeset cannot exist.
  const consumed = consumedChangesets(from);
  if (consumed.length > 0) {
    const withoutBump = changed.filter((name) => !versionIncreased(name, from));
    if (withoutBump.length === 0) {
      console.log(
        `This range applied ${consumed.length} changeset(s) and increased the version of every ` +
          'changed package, so it is a release and needs no changeset of its own.',
      );
      return;
    }
    console.log(
      `This range deleted ${consumed.length} changeset file(s) but did not increase the version of ` +
        `${withoutBump.join(', ')}, so it is not a release and still needs changesets.`,
    );
  }

  const { ignore } = readChangesetsConfig(root);
  const readChangesets = (await import('@changesets/read')).default;
  const changesets = await readChangesets(root, baseRef);

  const failures = [];
  const declared = new Map();
  for (const changeset of changesets) {
    for (const release of changeset.releases) {
      if (ignore.includes(release.name)) {
        failures.push(
          `.changeset/${changeset.id}.md releases ${release.name}, which .changeset/config.json ignores.`,
        );
        continue;
      }
      if (!PUBLISHABLE_PACKAGES.includes(release.name)) {
        failures.push(
          `.changeset/${changeset.id}.md releases ${release.name}, which is not a published package.`,
        );
        continue;
      }
      const existing = declared.get(release.name) ?? [];
      existing.push(`${release.type} in .changeset/${changeset.id}.md`);
      declared.set(release.name, existing);
    }
  }

  for (const name of changed.filter((candidate) => !declared.has(candidate))) {
    failures.push(
      `${name}: publishable package inputs changed but no changeset in this range releases it. ` +
        'Run `pnpm changeset` and name it, or name it at `patch` if you are unsure — a release you ' +
        'did not need costs less than a published version that means nothing.',
    );
  }

  if (failures.length > 0) {
    console.error(
      [
        'Every @openmaic publishable package change must ship with a changeset that names it:',
        ...failures.map((failure) => `- ${failure}`),
      ].join('\n'),
    );
    process.exit(1);
  }

  for (const name of changed) {
    console.log(`${name}: declared ${declared.get(name).join(', ')}.`);
  }
  console.log('Changeset check passed.');
}

const args = process.argv.slice(2);
if (args.length !== 1 || args[0].startsWith('--')) {
  console.error(usage);
  process.exit(2);
}
await main(args[0]);
